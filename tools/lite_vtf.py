"""lite_vtf.py <workshop id> <out_dir> [--skip-normals]  - re-encode an add-on's UNCOMPRESSED textures as DXT, same resolution.

For each .vtf in the add-on (VTF 7.2/7.3+ with a single frame/face/slice):
  - BGRA8888 / RGBA8888 / ABGR8888 / ARGB8888 / BGRX8888 / BGR888 / RGB888 top mip -> 32-bit DDS -> texconv
  - alpha all 255 (or no alpha channel)  -> BC1 (DXT1), EIGHTBITALPHA/ONEBITALPHA flags cleared
  - alpha used                           -> BC3 (DXT5)
  - full mip chain regenerated by texconv (same count as the original), low-res thumbnail copied unchanged
  - written as VTF 7.2 with the original header fields (flags, reflectivity, bumpscale, frames) otherwise unchanged
Skips: already-compressed textures, vgui/ (HUD icons), anything under 64 px, multi-frame/cubemap/volume textures.
Writes <out_dir>/<same relative path>.vtf so a local add-on built from <out_dir> overrides only those textures.
Uses tools/bin/texconv.exe (Microsoft DirectXTex). Read-only on the game install.
"""
import os, sys, struct, subprocess, tempfile, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from conflict_scan import index, read, G

TEXCONV = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bin', 'texconv.exe')
UNCOMP = {12: ('BGRA', 4), 0: ('RGBA', 4), 1: ('ABGR', 4), 11: ('ARGB', 4), 16: ('BGRX', 4), 3: ('BGR', 3), 2: ('RGB', 3)}
DXT1, DXT5 = 13, 15
FLAG_ONEBITALPHA, FLAG_EIGHTBITALPHA = 0x1000, 0x2000
LOWRES_BYTES = lambda fmt, w, h: 0 if fmt in (-1, 0xFFFFFFFF) or w == 0 else max(1, (w + 3) // 4) * max(1, (h + 3) // 4) * (8 if fmt == DXT1 else 16)


def to_bgra(raw, kind):
    if kind == 'BGRA':
        return raw
    out = bytearray(len(raw) // (3 if kind in ('BGR', 'RGB') else 4) * 4)
    if kind == 'BGR':
        out[0::4], out[1::4], out[2::4], out[3::4] = raw[0::3], raw[1::3], raw[2::3], b'\xff' * (len(raw) // 3)
    elif kind == 'RGB':
        out[0::4], out[1::4], out[2::4], out[3::4] = raw[2::3], raw[1::3], raw[0::3], b'\xff' * (len(raw) // 3)
    elif kind == 'RGBA':
        out[0::4], out[1::4], out[2::4], out[3::4] = raw[2::4], raw[1::4], raw[0::4], raw[3::4]
    elif kind == 'ABGR':
        out[0::4], out[1::4], out[2::4], out[3::4] = raw[1::4], raw[2::4], raw[3::4], raw[0::4]
    elif kind == 'ARGB':
        out[0::4], out[1::4], out[2::4], out[3::4] = raw[3::4], raw[2::4], raw[1::4], raw[0::4]
    elif kind == 'BGRX':
        out[:] = raw; out[3::4] = b'\xff' * (len(raw) // 4)
    return bytes(out)


def dds_bgra(w, h, px):
    # DDS, A8R8G8B8 (memory order B,G,R,A), no mips
    hdr = struct.pack('<4sIIIIIII44sIIIIIIIIIIIII', b'DDS ', 124, 0x1 | 0x2 | 0x4 | 0x8 | 0x1000, h, w, w * 4, 0, 1, b'\0' * 44,
                      32, 0x41, 0, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000, 0x1000, 0, 0, 0, 0)
    return hdr + px


def mip_dims(w, h, n):
    return [(max(1, w >> i), max(1, h >> i)) for i in range(n)]


def convert(b, rel, tmp, skip_normals):
    if b[:4] != b'VTF\0':
        return None, 'not vtf'
    hdrsize = struct.unpack_from('<I', b, 12)[0]
    w, h, flags, frames = struct.unpack_from('<HHIH', b, 16)
    fmt = struct.unpack_from('<i', b, 52)[0]
    mips = b[56]
    lrfmt = struct.unpack_from('<i', b, 57)[0]
    lrw, lrh = b[61], b[62]
    if fmt not in UNCOMP:
        return None, 'already compressed / other format'
    if frames != 1 or flags & 0x4000 or (struct.unpack_from('<H', b, 63)[0] or 1) > 1:   # 0x4000 = ENVMAP (cube)
        return None, 'multi-frame/cubemap/volume'
    if rel.startswith('materials/vgui/') or max(w, h) < 64:
        return None, 'hud/tiny'
    if skip_normals and (flags & 0x80 or rel.rsplit('.', 1)[0].endswith(('_n', '_normal', '_nrm', '_bump'))):
        return None, 'normal map (skipped)'
    kind, bpp = UNCOMP[fmt]
    top = w * h * bpp
    raw = b[len(b) - top:]
    px = to_bgra(raw, kind)
    has_alpha = kind in ('BGRA', 'RGBA', 'ABGR', 'ARGB') and min(px[3::4]) < 255
    target = DXT5 if has_alpha else DXT1
    src = os.path.join(tmp, 'in.dds')
    open(src, 'wb').write(dds_bgra(w, h, px))
    outdir = os.path.join(tmp, 'out')
    os.makedirs(outdir, exist_ok=True)
    r = subprocess.run([TEXCONV, '-nologo', '-y', '-f', 'BC3_UNORM' if target == DXT5 else 'BC1_UNORM', '-m', str(mips),
                        '-if', 'BOX', '-o', outdir, src], capture_output=True, text=True)
    dds = os.path.join(outdir, 'in.dds')
    if r.returncode != 0 or not os.path.exists(dds):
        return None, 'texconv failed: ' + (r.stdout + r.stderr)[-300:]
    d = open(dds, 'rb').read()
    os.remove(dds)
    off = 128 + (20 if d[84:88] == b'DX10' else 0)
    bs = 8 if target == DXT1 else 16
    sizes = [max(1, (mw + 3) // 4) * max(1, (mh + 3) // 4) * bs for mw, mh in mip_dims(w, h, mips)]
    chain = []
    for sz in sizes:                       # DDS: largest first
        chain.append(d[off:off + sz]); off += sz
    if any(len(c) != s for c, s in zip(chain, sizes)):
        return None, 'unexpected dds size'
    nflags = flags & ~(FLAG_ONEBITALPHA | FLAG_EIGHTBITALPHA)
    if target == DXT5:
        nflags |= FLAG_EIGHTBITALPHA
    header = bytearray(b[:80])
    struct.pack_into('<II', header, 4, 7, 2)
    struct.pack_into('<I', header, 12, 80)
    struct.pack_into('<I', header, 20, nflags)
    struct.pack_into('<i', header, 52, target)
    lr = LOWRES_BYTES(lrfmt, lrw, lrh)
    lowres = b[hdrsize:hdrsize + lr] if lr else b''
    if hdrsize > 80 and lr:                # 7.3+: low-res lives where its resource entry says; find via resource table
        nres = struct.unpack_from('<I', b, 68)[0]
        for i in range(nres):
            tag, rflags, roff = struct.unpack_from('<3sBI', b, 80 + 8 * i)
            if tag == b'\x01\0\0':
                lowres = b[roff:roff + lr]
    out = bytes(header) + lowres + b''.join(reversed(chain))   # VTF: smallest mip first
    return out, '%dx%d %s -> %s  %.2f -> %.2f MB' % (w, h, kind, 'DXT5' if target == DXT5 else 'DXT1', len(b) / 2**20, len(out) / 2**20)


def main():
    wid, outroot = sys.argv[1], sys.argv[2]
    skip_normals = '--skip-normals' in sys.argv
    ix = index(G + '/left4dead2/addons/workshop/%s.vpk' % wid)
    tmp = tempfile.mkdtemp(prefix='litevtf_')
    before = after = 0
    try:
        for rel in sorted(k for k in ix if k.endswith('.vtf')):
            b = read(ix[rel])
            out, msg = convert(b, rel, tmp, skip_normals)
            if out is None:
                print('  keep  %-60s %s' % (rel[-60:], msg))
                continue
            path = os.path.join(outroot, rel.replace('/', os.sep))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, 'wb').write(out)
            before += len(b); after += len(out)
            print('  DXT   %-60s %s' % (rel[-60:], msg))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print('converted textures: %.1f MB -> %.1f MB (saved %.1f MB)' % (before / 2**20, after / 2**20, (before - after) / 2**20))


if __name__ == '__main__':
    main()
